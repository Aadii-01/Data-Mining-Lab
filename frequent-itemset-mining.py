import pandas as pd
import numpy as np
import matplotlib.pyplot as plt

# Student performance dataset
data = {
    "Student_ID": list(range(101, 116)),
    "Age": [18, 19, 20, 21, 22, 23, 19, 20,
            21, 22, 18, 23, 20, 21, 19],
    "City": ["Sangli", "Pune", "Kolhapur", "Mumbai",
             "Ratnagiri", "Nashik", "Pune", "Sangli",
             "Mumbai", "Kolhapur", "Nashik", "Ratnagiri",
             "Pune", "Sangli", "Mumbai"],
    "Department": ["IT", "CSE", "Mechanical", "IT",
                   "Electrical", "CSE", "IT", "Civil",
                   "Mechanical", "CSE", "Electrical", "Civil",
                   "CSE", "IT", "Mechanical"],
    "Marks": [78, 85, 72, 91, 68, 88, 82, 74,
              65, 90, 76, 71, 87, 80, 69]
}

df = pd.DataFrame(data)

print("Original Student Dataset:")
display(df)

print("\nDataset shape:", df.shape)
print("\nData types:")
print(df.dtypes)

generalized_df = df.copy()

# Concept hierarchy: exact age -> age group
age_bins = [17, 20, 23, 26]
age_labels = ["18-20", "21-23", "24-26"]

generalized_df["Age_Group"] = pd.cut(
    generalized_df["Age"],
    bins=age_bins,
    labels=age_labels,
    include_lowest=True
)

print("Age Generalization:")
display(
    generalized_df[
        ["Student_ID", "Age", "Age_Group"]
    ]
)

print("\nNumber of students in each age group:")
print(generalized_df["Age_Group"].value_counts().sort_index())

# City -> Region hierarchy
city_to_region = {
    "Sangli": "Western Maharashtra",
    "Pune": "Western Maharashtra",
    "Kolhapur": "Western Maharashtra",
    "Mumbai": "Konkan",
    "Ratnagiri": "Konkan",
    "Nashik": "North Maharashtra"
}

# Department -> Academic stream hierarchy
department_to_stream = {
    "IT": "Computing",
    "CSE": "Computing",
    "Mechanical": "Core Engineering",
    "Electrical": "Core Engineering",
    "Civil": "Core Engineering"
}

generalized_df["Region"] = generalized_df["City"].map(
    city_to_region
)

generalized_df["Academic_Stream"] = (
    generalized_df["Department"].map(
        department_to_stream
    )
)

print("Generalized Dataset:")
display(
    generalized_df[
        ["Student_ID", "City", "Region",
         "Department", "Academic_Stream"]
    ]
)

print("\nRegion mapping check:")
print("Unmapped cities:", generalized_df["Region"].isna().sum())
print("Unmapped departments:",
      generalized_df["Academic_Stream"].isna().sum())

department_summary = generalized_df.groupby(
    "Department"
).agg(
    Student_Count=("Student_ID", "count"),
    Average_Marks=("Marks", "mean"),
    Minimum_Marks=("Marks", "min"),
    Maximum_Marks=("Marks", "max"),
    Total_Marks=("Marks", "sum")
).reset_index()

department_summary["Average_Marks"] = (
    department_summary["Average_Marks"].round(2)
)

print("Department-wise Summary:")
display(department_summary)

age_summary = generalized_df.groupby(
    "Age_Group", observed=False
).agg(
    Student_Count=("Student_ID", "count"),
    Average_Marks=("Marks", "mean"),
    Maximum_Marks=("Marks", "max"),
    Minimum_Marks=("Marks", "min")
).reset_index()

age_summary["Average_Marks"] = (
    age_summary["Average_Marks"].round(2)
)

print("Age-group Summary:")
display(age_summary)

region_summary = generalized_df.groupby(
    "Region"
).agg(
    Student_Count=("Student_ID", "count"),
    Average_Marks=("Marks", "mean"),
    Total_Marks=("Marks", "sum")
).reset_index()

region_summary["Average_Marks"] = (
    region_summary["Average_Marks"].round(2)
)

stream_summary = generalized_df.groupby(
    "Academic_Stream"
).agg(
    Student_Count=("Student_ID", "count"),
    Average_Marks=("Marks", "mean")
).reset_index()

stream_summary["Average_Marks"] = (
    stream_summary["Average_Marks"].round(2)
)

print("Region-wise Summary:")
display(region_summary)

print("\nAcademic-stream Summary:")
display(stream_summary)

fig, axes = plt.subplots(1, 2, figsize=(12, 5))

axes[0].bar(
    department_summary["Department"],
    department_summary["Average_Marks"]
)
axes[0].set_title("Average Marks by Department")
axes[0].set_xlabel("Department")
axes[0].set_ylabel("Average Marks")
axes[0].tick_params(axis="x", rotation=45)

axes[1].bar(
    region_summary["Region"],
    region_summary["Student_Count"]
)
axes[1].set_title("Student Count by Region")
axes[1].set_xlabel("Region")
axes[1].set_ylabel("Number of Students")
axes[1].tick_params(axis="x", rotation=25)

plt.tight_layout()
plt.show()

