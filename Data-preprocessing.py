import pandas as pd
import numpy as np

# Create a student performance dataset
data = {
    "Student_ID": [101, 102, 103, 104, 105,
                   106, 107, 108, 109, 110],
    "Age": [18, 19, 20, 21, 22, 23, 20, 21, 19, 22],
    "Attendance": [55, 60, 65, 70, 75, 80, 85, 90, 95, 98],
    "Marks": [35, 45, 55, 65, 70, 75, 80, 85, 90, 96]
}

print("Name: Aaditya Shirke \n PRN: 23610074 \n Subject: DM Lab")

df = pd.DataFrame(data)

print("Original Dataset:")
display(df)

print("\nDataset Information:")
print("Number of records:", df.shape[0])
print("Number of attributes:", df.shape[1])
print("\nDescriptive Statistics:")
display(df.describe())

# Select numerical attributes for normalization
columns = ["Age", "Attendance", "Marks"]

# Apply Min-Max normalization manually
min_max_df = df.copy()

for col in columns:
    minimum = df[col].min()
    maximum = df[col].max()

    min_max_df[col] = (
        (df[col] - minimum) / (maximum - minimum)
    )

print("Min-Max Normalized Dataset:")
display(min_max_df)

print("\nVerification: Minimum and Maximum after normalization")
print(min_max_df[columns].agg(["min", "max"]))

# Apply Z-score normalization using population standard deviation
zscore_df = df.copy()

for col in columns:
    mean = df[col].mean()
    std = df[col].std(ddof=0)

    zscore_df[col] = (df[col] - mean) / std

print("Z-score Normalized Dataset:")
display(zscore_df)

print("\nVerification: Mean after normalization")
print(zscore_df[columns].mean().round(4))

print("\nVerification: Population Standard Deviation")
print(zscore_df[columns].std(ddof=0).round(4))

# Compare original and normalized values
comparison = pd.DataFrame({
    "Student_ID": df["Student_ID"]
})

for col in columns:
    comparison[f"Original_{col}"] = df[col]
    comparison[f"MinMax_{col}"] = min_max_df[col].round(3)
    comparison[f"ZScore_{col}"] = zscore_df[col].round(3)

print("Comparison of Original and Normalized Values:")
display(comparison)

# Compare statistical properties
summary = pd.DataFrame({
    "Original Mean": df[columns].mean(),
    "Original Std": df[columns].std(ddof=0),
    "Min-Max Mean": min_max_df[columns].mean(),
    "Min-Max Std": min_max_df[columns].std(ddof=0),
    "Z-score Mean": zscore_df[columns].mean(),
    "Z-score Std": zscore_df[columns].std(ddof=0)
})

print("\nStatistical Comparison:")
display(summary.round(4))

import matplotlib.pyplot as plt

# Plot Min-Max normalized values
min_max_df[columns].plot(
    kind="line",
    marker="o",
    figsize=(10, 5)
)

plt.title("Min-Max Normalized Student Attributes")
plt.xlabel("Student Index")
plt.ylabel("Normalized Value (0 to 1)")
plt.grid(True)
plt.legend(title="Attributes")
plt.show()

# Plot Z-score normalized values
zscore_df[columns].plot(
    kind="line",
    marker="o",
    figsize=(10, 5)
)

plt.title("Z-score Normalized Student Attributes")
plt.xlabel("Student Index")
plt.ylabel("Z-score")
plt.axhline(y=0, linestyle="--")
plt.grid(True)
plt.legend(title="Attributes")
plt.show()

