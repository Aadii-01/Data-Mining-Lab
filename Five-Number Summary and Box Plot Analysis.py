import pandas as pd
import numpy as np

print("Name of Student: Aaditya Shirke \n PRN: 23610074 \n Subject: DM Lab\n")

df = pd.read_excel("/content/Student_Preprocessing_Dataset_50_Records.xlsx")

df.head()

df.info()

df.describe(include='all')

"""Check missing values"""

df.isnull().sum()

"""Remove duplicate records"""

print(df.duplicated().sum())

df.drop_duplicates(inplace=True)

"""Data smoothing (Bin mean)"""

df["Attendance_Bin"] = pd.cut(df["Attendance"], bins=5)

df["Attendance_Smoothed"] = (
    df.groupby("Attendance_Bin")["Attendance"]
      .transform("mean")
)

print(df[["Attendance","Attendance_Smoothed"]].head())

"""Label encoding"""

df["Gender"] = pd.factorize(df["Gender"])[0]
df["Department"] = pd.factorize(df["Department"])[0]
df["City"] = pd.factorize(df["City"])[0]

df.head()

print(df["Gender"].unique())
print(df["Department"].unique())
print(df["City"].unique())

"""Min max normalization

```
xnorm = (x-xmin)/ (xmax-xmin)

```
"""

df["Attendance_Normalized"] = (
    (df["Attendance"] - df["Attendance"].min()) /
    (df["Attendance"].max() - df["Attendance"].min())
)

df["Marks_Normalized"] = (
    (df["Marks"] - df["Marks"].min()) /
    (df["Marks"].max() - df["Marks"].min())
)

df[["Attendance", "Attendance_Normalized",
    "Marks", "Marks_Normalized"]].head()

"""Z score standardization

```
Z =(X-u)/(alpha)
```
"""

df["Age_Standardized"] = (
    (df["Age"] - df["Age"].mean()) /
    df["Age"].std()
)

df["Attendance_Standardized"] = (
    (df["Attendance"] - df["Attendance"].mean()) /
    df["Attendance"].std()
)

df["Marks_Standardized"] = (
    (df["Marks"] - df["Marks"].mean()) /
    df["Marks"].std()
)

df[["Age", "Age_Standardized",
    "Attendance", "Attendance_Standardized",
    "Marks", "Marks_Standardized"]].head()

