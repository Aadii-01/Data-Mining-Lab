import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns

"""
# Step 1: Create the dataset
"""

data = [
    ["D1", "Sunny",    "Hot",  "High",   "Weak",   "No"],
    ["D2", "Sunny",    "Hot",  "High",   "Strong", "No"],
    ["D3", "Overcast", "Hot",  "High",   "Weak",   "Yes"],
    ["D4", "Rain",     "Mild", "High",   "Weak",   "Yes"],
    ["D5", "Rain",     "Cool", "Normal", "Weak",   "Yes"],
    ["D6", "Rain",     "Cool", "Normal", "Strong", "No"],
    ["D7", "Overcast", "Cool", "Normal", "Strong", "Yes"],
    ["D8", "Sunny",    "Mild", "High",   "Weak",   "No"],
    ["D9", "Sunny",    "Cool", "Normal", "Weak",   "Yes"],
    ["D10","Rain",     "Mild", "Normal", "Weak",   "Yes"],
    ["D11","Sunny",    "Mild", "Normal", "Strong", "Yes"],
    ["D12","Overcast", "Mild", "High",   "Strong", "Yes"],
    ["D13","Overcast", "Hot",  "Normal", "Weak",   "Yes"],
    ["D14","Rain",     "Mild", "High",   "Strong", "No"]
]

columns = [
    "Day", "Outlook", "Temperature",
    "Humidity", "Wind", "Play"
]

df = pd.DataFrame(data, columns=columns)
print("Name: Aaditya Shirke \n PRN:23610074 \n Subject: Data Mining Lab")

print("Original Dataset:")
display(df)

"""# Step 2: Separate features and target"""

X = df.drop(columns=["Day", "Play"])
y = df["Play"]

print("Features:")
display(X)

print("Target:")
display(y)

"""# Step 3: Encode categorical features"""

X_encoded = pd.get_dummies(X, dtype=int)

y_encoded = y.map({
    "No": 0,
    "Yes": 1
})

print("Encoded Features:")
display(X_encoded)

print("Encoded Target:")
display(y_encoded)

"""# Step 4: Split the dataset into training and testing sets"""

from sklearn.model_selection import train_test_split

X_train, X_test, y_train, y_test = train_test_split(
    X_encoded,
    y_encoded,
    test_size=0.30,
    random_state=42,
    stratify=y_encoded
)

print("Training data shape:", X_train.shape)
print("Testing data shape:", X_test.shape)

"""
# Step 5: Train the Naive Bayes classifier"""

from sklearn.naive_bayes import GaussianNB

model = GaussianNB()

model.fit(X_train, y_train)

print("Naive Bayes model trained successfully.")

"""# Step 6: Predict the test instances"""

y_pred = model.predict(X_test)

print("\nActual values:   ", list(y_test))
print("Predicted values:", list(y_pred))

"""

# Display predictions using class labels"""

results = pd.DataFrame({
    "Actual": y_test.map({0: "No", 1: "Yes"}),
    "Predicted": pd.Series(
        y_pred, index=y_test.index
    ).map({0: "No", 1: "Yes"})
})

print("\nTest Instance Classification:")
display(results)

"""# Step 7: Calculate evaluation metrics"""

from sklearn.metrics import (
    accuracy_score,
    precision_score,
    recall_score,
    f1_score,
    confusion_matrix,
    classification_report
)

accuracy = accuracy_score(y_test, y_pred)

precision = precision_score(
    y_test, y_pred, pos_label=1, zero_division=0
)

recall = recall_score(
    y_test, y_pred, pos_label=1, zero_division=0
)

f1 = f1_score(
    y_test, y_pred, pos_label=1, zero_division=0
)

print("\n========== MODEL PERFORMANCE ==========")
print(f"Accuracy  : {accuracy:.4f}")
print(f"Accuracy %: {accuracy * 100:.2f}%")
print(f"Precision : {precision:.4f}")
print(f"Recall    : {recall:.4f}")
print(f"F1-score  : {f1:.4f}")

"""# Step 8: Generate the confusion matrix"""

cm = confusion_matrix(
    y_test, y_pred, labels=[0, 1]
)

print("\nConfusion Matrix:")
print(cm)

plt.figure(figsize=(5, 4))

sns.heatmap(
    cm,
    annot=True,
    fmt="d",
    cmap="Blues",
    xticklabels=["No", "Yes"],
    yticklabels=["No", "Yes"]
)

plt.xlabel("Predicted")
plt.ylabel("Actual")
plt.title("Naive Bayes - Confusion Matrix")
plt.show()

"""# Step 9: Display the classification report"""

print("\nClassification Report:")
print(
    classification_report(
        y_test,
        y_pred,
        labels=[0, 1],
        target_names=["No", "Yes"],
        zero_division=0
    )
)

"""
# Step 10: Predict new instances
"""

new_data = pd.DataFrame({
    "Outlook": ["Sunny", "Overcast"],
    "Temperature": ["Cool", "Mild"],
    "Humidity": ["High", "High"],
    "Wind": ["Strong", "Strong"]
})

new_encoded = pd.get_dummies(
    new_data, dtype=int
)

new_encoded = new_encoded.reindex(
    columns=X_encoded.columns,
    fill_value=0
)

new_predictions = model.predict(new_encoded)

new_data["Prediction"] = pd.Series(
    new_predictions
).map({0: "No", 1: "Yes"})

print("\nPredictions for New Instances:")
display(new_data)

