"""**Program 2 — Gini Index, Information Gain & Gain Ratio**"""

import math

# Calculate entropy of a dataset
def entropy(data):
    total = len(data)

    if total == 0:
        return 0

    counts = data["Play"].value_counts()

    ent = 0

    for count in counts:
        p = count / total
        ent -= p * math.log2(p)

    return ent


# Calculate Gini impurity of a dataset
def gini(data):
    total = len(data)

    if total == 0:
        return 0

    counts = data["Play"].value_counts()

    g = 1

    for count in counts:
        p = count / total
        g -= p ** 2

    return g

def information_gain(data, attribute):

    total_entropy = entropy(data)

    weighted_entropy = 0

    for value in data[attribute].unique():

        subset = data[data[attribute] == value]

        weighted_entropy += (
            len(subset) / len(data)
        ) * entropy(subset)

    return total_entropy - weighted_entropy

def gini_index(data, attribute):

    weighted_gini = 0

    for value in data[attribute].unique():

        subset = data[data[attribute] == value]

        weighted_gini += (
            len(subset) / len(data)
        ) * gini(subset)

    return weighted_gini

def split_information(data, attribute):

    total = len(data)

    split_info = 0

    for value in data[attribute].unique():

        subset_size = len(
            data[data[attribute] == value]
        )

        p = subset_size / total

        if p > 0:
            split_info -= p * math.log2(p)

    return split_info

def gain_ratio(data, attribute):

    ig = information_gain(data, attribute)

    split_info = split_information(data, attribute)

    if split_info == 0:
        return 0

    return ig / split_info

