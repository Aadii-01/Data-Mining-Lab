import math

def entropy(data):
    total = len(data)

    if total == 0:
        return 0

    yes = sum(data["Play"] == "Yes")
    no = sum(data["Play"] == "No")

    entropy_value = 0

    for count in [yes, no]:
        if count > 0:
            p = count / total
            entropy_value -= p * math.log2(p)

    return entropy_value


def information_gain(df, attribute):
    total_entropy = entropy(df)
    weighted_entropy = 0

    for value in df[attribute].unique():
        subset = df[df[attribute] == value]
        weighted_entropy += (
            len(subset) / len(df)
        ) * entropy(subset)

    return total_entropy - weighted_entropy


