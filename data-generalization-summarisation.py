import pandas as pd
import numpy as np
import matplotlib.pyplot as plt

# Student marks dataset
marks = [12, 15, 16, 19, 22, 24,
         25, 28, 35, 40, 42, 48]

print("Name: Aaditya Shirke \n PRN: 23610074 \n Subject: DM Lab")

df = pd.DataFrame({
    "Student": [f"S{i}" for i in range(1, 13)],
    "Marks": marks
})

print("Original Dataset:")
display(df)

print("Number of observations:", len(marks))
print("Minimum marks:", min(marks))
print("Maximum marks:", max(marks))

# Divide the data into 3 equal-width bins
number_of_bins = 3

df["Equal_Width_Bin"] = pd.cut(
    df["Marks"],
    bins=number_of_bins,
    labels=["Bin 1", "Bin 2", "Bin 3"],
    include_lowest=True
)

print("Equal-Width Binning:")
display(df[["Student", "Marks", "Equal_Width_Bin"]])

print("\nValues in each bin:")
for bin_name, group in df.groupby(
    "Equal_Width_Bin", observed=False
):
    print(bin_name, ":", group["Marks"].tolist())

# Sort the observations and divide them into 3 equal-frequency bins
sorted_marks = sorted(marks)

number_of_bins = 3
equal_frequency_bins = np.array_split(
    np.array(sorted_marks),
    number_of_bins
)

print("Equal-Frequency Binning:")

for i, bin_values in enumerate(equal_frequency_bins, start=1):
    print(f"Bin {i}: {bin_values.tolist()}")
    print("Number of observations:", len(bin_values))

# Calculate bin means and medians
bin_results = []

for i, values in enumerate(equal_frequency_bins, start=1):
    values = values.tolist()

    mean_value = np.mean(values)
    median_value = np.median(values)

    bin_results.append({
        "Bin": f"Bin {i}",
        "Original Values": values,
        "Bin Mean": round(mean_value, 2),
        "Bin Median": round(median_value, 2),
        "Smoothed by Mean": [round(mean_value, 2)] * len(values),
        "Smoothed by Median": [round(median_value, 2)] * len(values)
    })

results_df = pd.DataFrame(bin_results)

print("Bin Means and Medians:")
display(results_df)

boundary_results = []

for i, values in enumerate(equal_frequency_bins, start=1):
    values = values.tolist()

    lower_boundary = min(values)
    upper_boundary = max(values)

    smoothed_values = []

    for value in values:
        if abs(value - lower_boundary) <= abs(value - upper_boundary):
            smoothed_values.append(lower_boundary)
        else:
            smoothed_values.append(upper_boundary)

    boundary_results.append({
        "Bin": f"Bin {i}",
        "Original Values": values,
        "Lower Boundary": lower_boundary,
        "Upper Boundary": upper_boundary,
        "Smoothed by Boundaries": smoothed_values
    })

boundary_df = pd.DataFrame(boundary_results)

print("Smoothing by Bin Boundaries:")
display(boundary_df)

# Flatten equal-frequency bins and their smoothed results
original_values = []
mean_values = []
median_values = []
boundary_values = []

for values in equal_frequency_bins:
    values = values.tolist()

    original_values.extend(values)
    mean_values.extend([np.mean(values)] * len(values))
    median_values.extend([np.median(values)] * len(values))

    low = min(values)
    high = max(values)

    for value in values:
        if abs(value - low) <= abs(value - high):
            boundary_values.append(low)
        else:
            boundary_values.append(high)

comparison = pd.DataFrame({
    "Original": original_values,
    "Bin Mean": mean_values,
    "Bin Median": median_values,
    "Bin Boundaries": boundary_values
})

comparison.plot(
    kind="line",
    marker="o",
    figsize=(11, 6)
)

plt.title("Comparison of Binning and Smoothing Techniques")
plt.xlabel("Observation Index (Sorted)")
plt.ylabel("Marks")
plt.xticks(range(len(original_values)),
           range(1, len(original_values) + 1))
plt.grid(True)
plt.show()

print("Final Comparison Table:")
display(comparison.round(2))

