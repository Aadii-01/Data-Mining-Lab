import pandas as pd
from itertools import combinations

print("Name of Student: Aaditya Shirke \n PRN: 23610074 \n Subject: DM Lab\n")

transactions = [
    ['Bread', 'Milk', 'Butter'],
    ['Bread', 'Milk'],
    ['Bread', 'Butter'],
    ['Milk', 'Butter', 'Eggs'],
    ['Bread', 'Milk', 'Butter'],
    ['Milk', 'Eggs'],
    ['Bread', 'Milk', 'Eggs'],
    ['Bread', 'Butter']
]

min_support = 0.25
total_transactions = len(transactions)

print("Total transactions:", total_transactions)
print("Minimum support:", min_support)

"""Get all unique items"""

items = sorted(set(item for transaction in transactions
                   for item in transaction))

"""Store frequent itemsets and their support values"""

frequent_itemsets = {}
previous_frequent = set()

k = 1

while True:
    candidates = list(combinations(items, k))

    current_frequent = set()

    for candidate in candidates:

        # Apply the Apriori principle
        if k > 1:
            subsets = combinations(candidate, k - 1)

            if not all(frozenset(subset) in previous_frequent
                       for subset in subsets):
                continue

        # Count transactions containing the candidate
        count = sum(
            set(candidate).issubset(set(transaction))
            for transaction in transactions
        )

        support = count / total_transactions

        if support >= min_support:
            itemset = frozenset(candidate)
            current_frequent.add(itemset)

            frequent_itemsets[itemset] = {
                'Support Count': count,
                'Support': support
            }

    if not current_frequent:
        break

    previous_frequent = current_frequent
    k += 1

"""Display frequent itemsets"""

results = []

for itemset, values in frequent_itemsets.items():
    results.append({
        'Itemset': ', '.join(sorted(itemset)),
        'Support Count': values['Support Count'],
        'Support (%)': values['Support'] * 100
    })

result_df = pd.DataFrame(results)

print("Frequent Itemsets:")
display(result_df)

"""Display frequent itemsets level-wise"""

for size in range(1, len(items) + 1):
    print(f"\nFrequent {size}-itemsets:")

    for itemset, values in frequent_itemsets.items():
        if len(itemset) == size:
            print(
                f"{sorted(itemset)} -> "
                f"Support Count: {values['Support Count']}, "
                f"Support: {values['Support'] * 100:.2f}%"
            )

