# Commented out IPython magic to ensure Python compatibility.

# %pip -q install mlxtend

import pandas as pd
from mlxtend.preprocessing import TransactionEncoder
from mlxtend.frequent_patterns import apriori, association_rules

import warnings
warnings.filterwarnings("ignore", category=DeprecationWarning)

import pandas as pd

transactions = [
    ["Bread", "Milk"],
    ["Bread", "Butter", "Milk"],
    ["Bread", "Butter"],
    ["Milk", "Butter"],
    ["Bread", "Milk", "Butter"],
    ["Bread", "Eggs", "Milk"],
    ["Bread", "Milk"],
    ["Butter", "Eggs", "Milk"]
]

transaction_df = pd.DataFrame({
    "Transaction_ID": [
        f"T{i}" for i in range(1, len(transactions) + 1)
    ],
    "Items": [", ".join(items) for items in transactions]
})

print("Transaction Dataset:")
display(transaction_df)

encoder = TransactionEncoder()

encoded_array = encoder.fit(transactions).transform(transactions)

basket_df = pd.DataFrame(
    encoded_array,
    columns=encoder.columns_
)

print("One-Hot Encoded Transaction Matrix:")
display(basket_df)

frequent_itemsets = apriori(
    basket_df,
    min_support=0.25,
    use_colnames=True
)

frequent_itemsets["itemsets"] = frequent_itemsets[
    "itemsets"
].apply(lambda items: ", ".join(sorted(items)))

print("Frequent Itemsets:")
display(
    frequent_itemsets.sort_values(
        ["support", "itemsets"],
        ascending=[False, True]
    ).reset_index(drop=True)
)

# Generate rules using a minimum confidence of 60%
rules = association_rules(
    apriori(
        basket_df,
        min_support=0.25,
        use_colnames=True
    ),
    metric="confidence",
    min_threshold=0.60
)

# Make the output easier to read
rules["antecedents"] = rules["antecedents"].apply(
    lambda items: ", ".join(sorted(items))
)
rules["consequents"] = rules["consequents"].apply(
    lambda items: ", ".join(sorted(items))
)

rules = rules.sort_values(
    ["lift", "confidence"],
    ascending=False
)

print("Association Rules:")
display(
    rules[
        ["antecedents", "consequents",
         "support", "confidence", "lift"]
    ].round(3).reset_index(drop=True)
)

# Select rules with confidence >= 70% and lift > 1
strong_rules = rules[
    (rules["confidence"] >= 0.70) &
    (rules["lift"] > 1)
]

print("Strong Positive Association Rules:")
display(
    strong_rules[
        ["antecedents", "consequents",
         "support", "confidence", "lift"]
    ].round(3).reset_index(drop=True)
)

if not strong_rules.empty:
    best_rule = strong_rules.iloc[0]

    print("\nExample Rule Interpretation:")
    print(
        f"If a transaction contains {best_rule['antecedents']}, "
        f"it also contains {best_rule['consequents']} "
        f"in {best_rule['confidence']:.1%} of cases "
        f"containing the antecedent."
    )
    print(f"Support: {best_rule['support']:.1%}")
    print(f"Confidence: {best_rule['confidence']:.1%}")
    print(f"Lift: {best_rule['lift']:.3f}")
else:
    print("No rules satisfy the selected thresholds.")

import matplotlib.pyplot as plt

if not rules.empty:
    plt.figure(figsize=(8, 5))

    plt.scatter(
        rules["support"],
        rules["confidence"],
        s=rules["lift"] * 300,
        alpha=0.7
    )

    plt.xlabel("Support")
    plt.ylabel("Confidence")
    plt.title("Association Rules: Support vs Confidence")
    plt.grid(True)
    plt.show()
else:
    print("No association rules are available to plot.")

